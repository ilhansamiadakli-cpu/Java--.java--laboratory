public class Diziler {
public static void main(String[] args) {
        int[] dizi = new int[5];
        dizi[0] = 10;
        dizi[1] = 20;
        dizi[2] = 30;
        dizi[3] = 40;
        dizi[4] = 50;

        System.out.println("Dizinin elemanları:");
        for(int sayı:dizi){
            System.out.println(sayı);
        }
    }
}
